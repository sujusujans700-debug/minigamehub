<?php

require_once __DIR__ . "/config.php";


header(
    "Content-Type: application/json"
);


/*
|--------------------------------------------------------------------------
| Get scores
|--------------------------------------------------------------------------
*/

$scores =
    readJson(SCORES_FILE);


/*
|--------------------------------------------------------------------------
| Sort highest score first
|--------------------------------------------------------------------------
*/

usort(
    $scores,
    function ($a, $b) {

        return
            ($b["score"] ?? 0) -
            ($a["score"] ?? 0);

    }
);


/*
|--------------------------------------------------------------------------
| Optional game filter
|--------------------------------------------------------------------------
*/

$game =
    trim($_GET["game"] ?? "");


if ($game !== "") {

    $scores =
        array_values(
            array_filter(
                $scores,
                function ($item) use ($game) {

                    return
                        strtolower(
                            $item["game"] ?? ""
                        ) ===
                        strtolower($game);

                }
            )
        );

}


/*
|--------------------------------------------------------------------------
| Limit
|--------------------------------------------------------------------------
*/

$limit =
    isset($_GET["limit"])
        ? (int)$_GET["limit"]
        : 100;


if ($limit < 1) {

    $limit = 100;

}


$scores =
    array_slice(
        $scores,
        0,
        $limit
    );


/*
|--------------------------------------------------------------------------
| Return data
|--------------------------------------------------------------------------
*/

echo json_encode([

    "success" => true,

    "scores" => $scores

]);